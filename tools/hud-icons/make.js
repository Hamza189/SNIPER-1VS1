/* Builds the HUD icon pack from tools/hud-icons/icons.js:
     assets/hud/icons/<name>[_pressed|_active|_alert].svg   one file per state
     assets/hud/icons/variants/<name>_<a|b|c>.svg           alternatives for the doubtful ones
     assets/hud/icons/weapons/weapon_<id>.svg               silhouettes for the weapon bar
     assets/hud/png/<64|96|128|256>/<file>.png              raster copies (Playwright + Chromium)
     assets/hud/sprites/hud_icons_<128>.png + .json          sprite sheet (optional use)
     assets/hud/preview/preview_dark.png, preview_light.png, variants.png
     assets/hud/hud_icons.json                               name → files, action, toggle, states
     client/hudicons.js                                      glyphs inlined for the game (no fetch)
   Run: node tools/hud-icons/make.js   (add --no-png to skip the raster part) */
'use strict';
const fs = require('fs'), path = require('path');
const I = require('./icons.js');
const root = path.join(__dirname, '..', '..'), out = path.join(root, 'assets', 'hud');
const mk = d => fs.mkdirSync(d, { recursive: true });
const write = (f, s) => { mk(path.dirname(f)); fs.writeFileSync(f, s); };
const RECOMMENDED = { peak_left: 'a', peak_right: 'a', inspect: 'a', hold_breath: 'a' };
const SIZES = [64, 96, 128, 256];

const files = [];   // { file (relative to assets/hud), svg, w, h }
const map = { version: 1, grid: 64, stroke: 3.5, icons: {}, weapons: {} };
for (const name in I.GLYPHS) {
  const G = I.GLYPHS[name], st = I.states(name), entry = { action: G.action, toggle: !!I.TOGGLE[name], states: {} };
  if (I.TOGGLE[name]) entry.toggleNote = I.TOGGLE[name];
  if (I.ALERT[name]) entry.alertNote = I.ALERT[name];
  if (G.note) entry.note = G.note;
  for (const s of st) {
    const f = 'icons/' + name + (s === 'normal' ? '' : '_' + s) + '.svg';
    files.push({ file: f, svg: I.iconSVG(name, s), w: 64, h: 64 }); entry.states[s] = f;
  }
  if (G.variants) {
    entry.variants = {}; entry.recommended = RECOMMENDED[name];
    for (const v in G.variants) { const f = 'icons/variants/' + name + '_' + v + '.svg'; files.push({ file: f, svg: I.iconSVG(name, 'normal', v), w: 64, h: 64 }); entry.variants[v] = f; }
  }
  map.icons[name] = entry;
}
for (const id in I.WEAPONS) {
  const f = 'icons/weapons/weapon_' + id + '.svg';
  files.push({ file: f, svg: I.weaponSVG(id, '#f2efe8'), w: 120, h: 40 }); map.weapons[id] = { name: I.WEAPONS[id].name, file: f };
}
for (const f of files) write(path.join(out, f.file), f.svg + '\n');
write(path.join(out, 'hud_icons.json'), JSON.stringify(map, null, 2) + '\n');

// the game's copy: glyph only (coloured by CSS currentColor) + weapon silhouettes
const glyphs = {}, weapons = {};
for (const name in I.GLYPHS) glyphs[name] = I.glyphSVG(name);
for (const id in I.WEAPONS) weapons[id] = I.weaponSVG(id);
write(path.join(root, 'client', 'hudicons.js'),
  '/* SNIPER DUEL — HUD icons (generated by tools/hud-icons/make.js: do not edit by hand). Glyphs use currentColor. */\n' +
  '(function (root) {\n\'use strict\';\nconst SDHudIcons = ' + JSON.stringify({ glyphs, weapons }, null, 0).replace(/","/g, '",\n"') + ';\n' +
  'if (typeof module !== \'undefined\' && module.exports) module.exports = SDHudIcons; else root.SDHudIcons = SDHudIcons;\n})(typeof window !== \'undefined\' ? window : globalThis);\n');
console.log('svg: ' + files.length + ' archivos · client/hudicons.js');

if (process.argv.includes('--no-png')) process.exit(0);
(async () => {
  let chromium; try { ({ chromium } = require(path.join(root, 'node_modules', 'playwright'))); } catch (e) { console.log('playwright no está: sin PNG'); return; }
  const b = await chromium.launch(), page = await b.newPage();
  const shot = async (html, w, h, file, transparent) => {
    await page.setViewportSize({ width: w, height: h });
    await page.setContent('<html><body style="margin:0;background:transparent">' + html + '</body></html>');
    mk(path.dirname(file)); await page.screenshot({ path: file, omitBackground: !!transparent, clip: { x: 0, y: 0, width: w, height: h } });
  };
  let n = 0;
  for (const f of files) for (const s of SIZES) {
    const w = f.w === 64 ? s : s * 120 / 40 | 0, h = f.w === 64 ? s : s;
    const svg = f.svg.replace(/width="\d+" height="\d+"/, 'width="' + w + '" height="' + h + '"');
    await shot('<div style="width:' + w + 'px;height:' + h + 'px;line-height:0">' + svg + '</div>', w, h, path.join(out, 'png', String(s), f.file.replace(/^icons\//, '').replace(/\.svg$/, '.png')), true); n++;
  }
  // sprite sheet: every state file at 128 px, 8 per row
  const sheetFiles = files.filter(f => f.w === 64 && !/variants\//.test(f.file)), S = 128, cols = 8, rows = Math.ceil(sheetFiles.length / cols), frames = {};
  let html = '<div style="position:relative;width:' + cols * S + 'px;height:' + rows * S + 'px">';
  sheetFiles.forEach((f, i) => { const x = (i % cols) * S, y = (i / cols | 0) * S; frames[path.basename(f.file, '.svg')] = { x, y, w: S, h: S };
    html += '<div style="position:absolute;left:' + x + 'px;top:' + y + 'px;line-height:0">' + f.svg.replace('width="64" height="64"', 'width="' + S + '" height="' + S + '"') + '</div>'; });
  await shot(html + '</div>', cols * S, rows * S, path.join(out, 'sprites', 'hud_icons_128.png'), true);
  write(path.join(out, 'sprites', 'hud_icons_128.json'), JSON.stringify({ image: 'hud_icons_128.png', size: S, frames }, null, 1) + '\n');
  // previews on dark and light backgrounds (the game is played over both: night interiors and bright sky)
  const grid = (bg, fg) => {
    let h = '<div style="background:' + bg + ';padding:18px;width:1164px;font:600 12px monospace;color:' + fg + ';display:flex;flex-wrap:wrap;gap:14px 10px">';
    for (const name in I.GLYPHS) {
      h += '<div style="width:136px;text-align:center"><div style="display:flex;gap:4px;justify-content:center;align-items:center">';
      for (const s of I.states(name)) h += I.iconSVG(name, s).replace('width="64" height="64"', 'width="' + (s === 'normal' ? 64 : 40) + '" height="' + (s === 'normal' ? 64 : 40) + '"');
      h += '</div><div style="margin-top:4px">' + name + '</div><div style="opacity:.6;line-height:0;margin-top:4px">' + I.iconSVG(name, 'normal').replace('width="64" height="64"', 'width="32" height="32"') + '</div></div>';
    }
    h += '<div style="width:100%;display:flex;gap:24px;align-items:center;margin-top:8px">';
    for (const id in I.WEAPONS) h += '<div style="color:' + fg + ';text-align:center">' + I.weaponSVG(id).replace('aria-hidden="true"', 'width="180" height="60"') + '<div>weapon_' + id + '</div></div>';
    return h + '</div></div>';
  };
  for (const [nm, bg, fg] of [['preview_dark', '#15130f', '#e9e4da'], ['preview_light', '#c9d3db', '#1d1b18']]) {
    await page.setViewportSize({ width: 1200, height: 400 }); await page.setContent('<html><body style="margin:0">' + grid(bg, fg) + '</body></html>');
    mk(path.join(out, 'preview')); await page.locator('body>div').screenshot({ path: path.join(out, 'preview', nm + '.png') });
  }
  // the variants side by side (recommended one marked)
  let vh = '<div style="background:#15130f;padding:18px;font:600 13px monospace;color:#e9e4da;display:grid;gap:14px;width:700px">';
  for (const name in I.GLYPHS) { const G = I.GLYPHS[name]; if (!G.variants) continue;
    vh += '<div style="display:flex;gap:18px;align-items:center"><div style="width:130px">' + name + '</div>';
    for (const v in G.variants) vh += '<div style="text-align:center">' + I.iconSVG(name, 'normal', v).replace('width="64" height="64"', 'width="72" height="72"') + '<div style="color:' + (RECOMMENDED[name] === v ? '#ffc247' : '#9a9387') + '">' + v + (RECOMMENDED[name] === v ? ' ★ recomendado' : '') + '</div></div>';
    vh += '</div>'; }
  await page.setViewportSize({ width: 760, height: 400 }); await page.setContent('<html><body style="margin:0">' + vh + '</div></body></html>');
  await page.locator('body>div').screenshot({ path: path.join(out, 'preview', 'variants.png') });
  await b.close();
  console.log('png: ' + n + ' archivos · hoja de sprites · 3 vistas previas');
})();
