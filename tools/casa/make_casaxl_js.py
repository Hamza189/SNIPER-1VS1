"""CASA ATLAS XL (40 × 32 m, ChatGPT 18-10-2026) → client/casaxl.js: the collision boxes the page builds the map from.
Source: assets/maps/casa_atlas_xl/collision_map.json (exact copy of the delivery in assets/3d/imports/2026-10-18_casa_atlas_xl/).
Every box becomes {n, s, a:[minX,minY,minZ], b:[maxX,maxY,maxZ], f}: s = 1 solid (movement + bullets), 0 movement only (glass);
f = impact surface. The map is CLIENT ONLY for now (duel vs bots, ?casa=2): tools/export-map.js skips it, so the server
(core/mapdata.js) does not change until the owner approves deploying it. Run: python3 tools/casa/make_casaxl_js.py"""
import json, os
R = os.path.join(os.path.dirname(__file__), '..', '..'); A = os.path.join(R, 'assets/maps/casa_atlas_xl')
D = json.load(open(os.path.join(A, 'collision_map.json'), encoding='utf-8'))
r3 = lambda v: round(v + 0.0, 3)
SURF = [('estanque', 'concrete'), ('macetero', 'concrete'), ('banco', 'wood'), ('caja', 'wood'), ('pergola', 'wood'), ('olivo', 'wood'),
        ('isla', 'wood'), ('aparador', 'wood'), ('mesa', 'wood'), ('silla', 'wood'), ('armario', 'wood'), ('modulo', 'wood'),
        ('sofa', 'dirt'), ('cama', 'dirt'), ('garaje_cajon', 'metal'), ('garaje_almacen', 'metal')]
def surf(n):
    for k, v in SURF:
        if n.startswith(k): return v
    return 'plaster'
boxes = []
for c in D['colliders']:
    lo = [r3(c['center'][i] - c['size'][i] / 2) for i in range(3)]; hi = [r3(c['center'][i] + c['size'][i] / 2) for i in range(3)]
    boxes.append({'n': c['name'], 's': 1 if c['type'] == 'solid' else 0, 'a': lo, 'b': hi, 'f': surf(c['name'])})
out = {'id': D['id'], 'version': D['version'], 'bounds': D['bounds'],
       'spawns': [{'team': s['team'], 'x': s['position'][0], 'z': s['position'][2], 'yaw': s['yaw']} for s in D['spawns']],
       'zones': D['zones'], 'boxes': boxes}
js = ('/* GENERATED by tools/casa/make_casaxl_js.py from assets/maps/casa_atlas_xl/collision_map.json (ChatGPT, untouched).\n'
      '   CASA ATLAS XL, experimental map (?casa=2), client only for now: the page builds its collision and bullet boxes from\n'
      '   this. Do not edit by hand. */\n'
      '(function (root) {\n\'use strict\';\nconst SDCasaXL = ' + json.dumps(out, separators=(',', ':')) + ';\n'
      "if (typeof module !== 'undefined' && module.exports) module.exports = SDCasaXL; else root.SDCasaXL = SDCasaXL;\n"
      "})(typeof window !== 'undefined' ? window : globalThis);\n")
open(os.path.join(R, 'client/casaxl.js'), 'w', encoding='utf-8', newline='\n').write(js)
print('client/casaxl.js:', len(boxes), 'cajas (', sum(b['s'] for b in boxes), 'sólidas,', sum(1 - b['s'] for b in boxes), 'solo movimiento )')
