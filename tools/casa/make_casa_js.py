"""CASA ATLAS 1V1 → client/casa.js: the collision boxes the page builds the map from (and, through tools/export-map.js,
the server: core/mapdata.js). Source: assets/maps/casa_atlas/collision_map.json (ChatGPT, untouched) + collision_fixes.json
(Claude). Every box becomes {n, s, a:[minX,minY,minZ], b:[maxX,maxY,maxZ], f}: s = 1 solid (movement + bullets), 0 movement only;
f = impact surface. Run: python3 tools/casa/make_casa_js.py"""
import json, os
R = os.path.join(os.path.dirname(__file__), '..', '..'); A = os.path.join(R, 'assets/maps/casa_atlas')
D = json.load(open(os.path.join(A, 'collision_map.json'))); F = json.load(open(os.path.join(A, 'collision_fixes.json')))
r3 = lambda v: round(v + 0.0, 3)
SURF = {'fridge': 'metal', 'oven': 'metal', 'toilet': 'concrete', 'shower_tray': 'concrete', 'sink_vanity': 'wood', 'kitchen_island': 'wood',
        'kitchen_counter_unit': 'wood', 'sofa': 'dirt', 'bed': 'dirt', 'coffee': 'wood', 'media': 'wood', 'book': 'wood', 'office': 'wood',
        'wardrobe': 'wood', 'bedside': 'wood', 'hall': 'wood', 'dining': 'wood', 'desk': 'wood', 'wall': 'plaster'}
def surf(n):
    for k, v in SURF.items():
        if n.startswith(k): return v
    return 'plaster'
boxes = []
for c in D['colliders']:
    lo = [r3(c['center'][i] - c['size'][i] / 2) for i in range(3)]; hi = [r3(c['center'][i] + c['size'][i] / 2) for i in range(3)]
    boxes.append({'n': c['name'], 's': 1 if c['type'] == 'solid' else 0, 'a': lo, 'b': hi, 'f': surf(c['name'])})
for c in F['solid']: boxes.append({'n': c['name'], 's': 1, 'a': c['min'], 'b': c['max'], 'f': c.get('surf', 'plaster')})
for c in F['move']: boxes.append({'n': c['name'], 's': 0, 'a': c['min'], 'b': c['max'], 'f': ''})
SP = F.get('spawns', {})
out = {'id': D['id'], 'version': D['version'], 'spawns': [{'team': s['team'], 'x': SP.get(s['team'], {}).get('x', s['position'][0]), 'z': SP.get(s['team'], {}).get('z', s['position'][2]), 'yaw': s['yaw']} for s in D['spawns']],
       'zones': D['zones'], 'boxes': boxes}
js = ('/* GENERATED by tools/casa/make_casa_js.py from assets/maps/casa_atlas/collision_map.json (ChatGPT) + collision_fixes.json (Claude).\n'
      '   CASA ATLAS 1V1, experimental map: the page builds its collision and bullet boxes from this; the server gets them through\n'
      '   tools/export-map.js → core/mapdata.js. Do not edit by hand. */\n'
      '(function (root) {\n\'use strict\';\nconst SDCasa = ' + json.dumps(out, separators=(',', ':')) + ';\n'
      "if (typeof module !== 'undefined' && module.exports) module.exports = SDCasa; else root.SDCasa = SDCasa;\n"
      "})(typeof window !== 'undefined' ? window : globalThis);\n")
open(os.path.join(R, 'client/casa.js'), 'w').write(js)
print('client/casa.js:', len(boxes), 'cajas (', sum(b['s'] for b in boxes), 'sólidas,', sum(1 - b['s'] for b in boxes), 'solo movimiento )')
